    /// <summary>填充（fill）渲染的图标，而不是描边（stroke）。垃圾桶这类「线性」图标由用户提供 fill path。</summary>
    private static readonly HashSet<string> Filled = new(StringComparer.Ordinal)
    {
        Glyphs.Trash,
        Glyphs.BookClosed,
        Glyphs.Tray,
        Glyphs.Chart,
        Glyphs.Tag,
        Glyphs.Folder,
    };

    /// <summary>
    /// 启动自检：逐个解析路径，任何一条语法不兼容都会写到 stderr，
    /// 避免某个图标悄悄回退成 emoji / 豆腐块却没人发现。
    /// </summary>
    static Icons()
    {
        foreach (var pair in Paths)
        {
            try { StreamGeometry.Parse(pair.Value); }
            catch (Exception ex)
            {
                Console.Error.WriteLine("[Tonote.Icons] 路径解析失败: " + pair.Key + " / " + ex.Message);
            }
        }
    }

    /// <summary>矢量图标；找不到对应路径或路径解析失败时返回 null，让调用方回退成文字。</summary>
    public static Control? Vector(string glyph, double size, IBrush color)
    {
        if (!Paths.TryGetValue(glyph, out var markup))
            return null;
        Geometry geometry;
        try { geometry = StreamGeometry.Parse(markup); }
        catch { return null; }

        var filled = Filled.Contains(glyph);
        return new AvaloniaPath
        {
            Data = geometry,
            // 填充类图标走 Fill；描边类走 Stroke（空态大图标若沿用 1.7 会过细，按尺寸微调）
            Stroke = filled ? null : color,
            StrokeThickness = filled ? 0 : (size >= 28 ? 2.2 : 1.7),
            StrokeLineCap = PenLineCap.Round,
            StrokeJoin = PenLineJoin.Round,
            Fill = filled ? color : null,
            Stretch = Stretch.Uniform,
            Width = size,
            Height = size,
            HorizontalAlignment = HorizontalAlignment.Center,
            VerticalAlignment = VerticalAlignment.Center,
        };
    }

    /// <summary>有矢量用矢量，没有（例如 B / I / U / 字号数字）保留文字按钮。</summary>
    public static Control Render(string glyph, double size, IBrush color)
        => Vector(glyph, size, color) ?? new TextBlock
        {
            Text = glyph,
            FontSize = size,
            FontWeight = FontWeight.Medium,
            Foreground = color,
            HorizontalAlignment = HorizontalAlignment.Center,
            VerticalAlignment = VerticalAlignment.Center,
            TextAlignment = TextAlignment.Center,
        };

    /// <summary>hover 换色：Path 填充类走 Fill、描边类走 Stroke，文字走 Foreground。</summary>
    public static void Tint(Control content, IBrush brush)
    {
        if (content is AvaloniaPath path)
        {
            if (path.Fill != null) path.Fill = brush;
            else path.Stroke = brush;
        }
        else if (content is TextBlock block) block.Foreground = brush;
    }
